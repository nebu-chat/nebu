defmodule Nebu.OAuth.SigningKeyStore do
  @moduledoc """
  Nebu's id_token signing keys (`oauth_signing_keys`, migration 000042) — story
  oauth-token-endpoint, T17 / T18 / AC13. ADR-018: inline SQL.

  ## Key (T17)

  ES256 (P-256), generated by Nebu (`JOSE.JWK.generate_key({:ec, "P-256"})`), `kid` = the RFC 7638
  thumbprint. The PRIVATE JWK (JSON) is stored ONLY as `Nebu.Web.SecretBox.encrypt/1` ciphertext,
  the PUBLIC JWK as `jsonb`. The key is never logged, never `inspect`ed and never part of an error
  tuple; errors are atoms only.

  ## Lazy, cluster-safe generation (T18)

  `ensure_active_key/0`: SELECT the active row; none => generate, `INSERT ... ON CONFLICT DO
  NOTHING` (the primary key and the partial UNIQUE index `oauth_signing_keys_one_active` allow at
  most ONE active row), SELECT again. Exactly one generator wins across the cluster; losers discard
  their key. No advisory lock and no node-local "which kid is active" state. An active row that
  exists but cannot be loaded (tampered / swapped ciphertext, SecretBox unavailable) is an error —
  a second key is never generated next to it (fail closed).

  Loading verifies that the decrypted private key's thumbprint equals `kid` AND that its public part
  equals the stored `public_jwk`: SecretBox has no associated data, so a ciphertext copied from
  another row must fail closed (`{:error, :key_inconsistent}`). The DECODED, verified key material
  is cached per node keyed by `kid` + ciphertext (immutable rows, guard trigger) — never the answer
  to "which kid is active".

  ## Rotation (story oauth-hardening-hygiene, HY11-HY13; migration 000047)

  Rotation is operator-driven, never automatic (`Nebu.Release.rotate_oauth_signing_key/0`, `bin/nebu rpc`):

    * `rotate/1`, call 1 (no `next` row): generate an ES256 key and INSERT it as `next` (in the JWKS, never
      signs). Call 2 (a `next` row older than 900 s that LOADS: decrypt + thumbprint + public part, as for the
      active key): in ONE transaction retire the active key (`not_after = now() + 900 s`) and promote `next`.
      The 900 s rule (JWKS max-age 600 s + id_token lifetime 300 s) is enforced by the database (guard trigger).
    * `replace_emergency/1`: for an active key that can no longer be decrypted (changed `NEBU_INTERNAL_SECRET`):
      in ONE transaction retire the active key and any `next` row and INSERT a fresh `active` key.

  Both take a transaction-scoped advisory lock first, so concurrent operators are serialized, and run the
  caller's REQUIRED `:audit` function inside the transaction (a failed audit rolls everything back); they
  return kids and atoms only. `published_keys/0` lists the active key first, then the `next` key, then retired
  keys with `not_after > now()`, newest first.

  The per-node cache of decoded keys lives in the ETS table `:nebu_oauth_signing_key_cache`, created and owned
  by `Nebu.OAuth.CacheOwner` (HY4): this module never creates a table; a missing table is a cache miss.

  Test seam: `:nebu_http, :oauth_repo` (same as `Nebu.OAuth.ClientStore` / `CodeStore`).
  """

  require Logger

  @alg "ES256"
  @cache_table :nebu_oauth_signing_key_cache

  @sql_active "SELECT kid, public_jwk, private_jwk_enc FROM oauth_signing_keys WHERE status = 'active'"

  @sql_insert """
  INSERT INTO oauth_signing_keys (kid, alg, public_jwk, private_jwk_enc, status)
  VALUES ($1, 'ES256', $2::text::jsonb, $3, 'active')
  ON CONFLICT DO NOTHING
  """

  @sql_published """
  SELECT public_jwk, kid FROM oauth_signing_keys
  WHERE status IN ('active', 'next') OR (status = 'retired' AND not_after > now())
  ORDER BY CASE status WHEN 'active' THEN 0 WHEN 'next' THEN 1 ELSE 2 END, created_at DESC
  """

  # The `next` row (locked), whether it is old enough (same predicate as the guard trigger of migration 000047) and
  # the seconds left until it is.
  @sql_next_for_update """
  SELECT kid, public_jwk, private_jwk_enc,
         created_at <= now() - interval '900 seconds',
         GREATEST(1, ceil(extract(epoch FROM (created_at + interval '900 seconds' - now()))))::int
  FROM oauth_signing_keys WHERE status = 'next' FOR UPDATE
  """

  @sql_active_kid "SELECT kid FROM oauth_signing_keys WHERE status = 'active'"

  @sql_insert_next """
  INSERT INTO oauth_signing_keys (kid, alg, public_jwk, private_jwk_enc, status)
  VALUES ($1, 'ES256', $2::text::jsonb, $3, 'next')
  ON CONFLICT DO NOTHING
  RETURNING created_at + interval '900 seconds'
  """

  @sql_insert_active_strict """
  INSERT INTO oauth_signing_keys (kid, alg, public_jwk, private_jwk_enc, status)
  VALUES ($1, 'ES256', $2::text::jsonb, $3, 'active')
  """

  @sql_retire_active """
  UPDATE oauth_signing_keys
  SET status = 'retired', retired_at = now(), not_after = now() + interval '900 seconds'
  WHERE status = 'active' RETURNING kid
  """

  # A `next` row that is discarded never signed anything: its publication window ends now.
  @sql_retire_next """
  UPDATE oauth_signing_keys
  SET status = 'retired', retired_at = now(), not_after = now()
  WHERE status = 'next'
  """

  @sql_promote "UPDATE oauth_signing_keys SET status = 'active' WHERE kid = $1 AND status = 'next'"

  @type key :: %{kid: String.t(), jwk: JOSE.JWK.t()}

  @doc """
  The active signing key, generated lazily when none exists. `{:ok, %{kid:, jwk:}}` or
  `{:error, :key_inconsistent | :key_unavailable | :storage}`. Never raises.
  """
  @spec ensure_active_key() :: {:ok, key()} | {:error, atom()}
  def ensure_active_key do
    case load_active() do
      {:ok, nil} -> generate_and_load()
      other -> other
    end
  rescue
    e ->
      Logger.warning("OAuth signing key: unexpected #{inspect(e.__struct__)}")
      {:error, :key_unavailable}
  end

  @doc """
  The PUBLIC JWKs to publish: the active key first, then the `next` key, then retired keys with
  `not_after > now()`, newest first. Each map has exactly `kty`, `crv`, `x`, `y`, `kid`, `use`, `alg`. Never raises.
  """
  @spec published_keys() :: {:ok, [map()]} | {:error, atom()}
  def published_keys do
    case query(@sql_published, []) do
      {:ok, %{rows: rows}} -> {:ok, Enum.map(rows, fn [pub, kid] -> public_member_map(decode_json(pub), kid) end)}
      {:error, _} -> {:error, :storage}
    end
  end

  @typedoc "Audit hook of the rotation functions: `(action, new_kid, metadata)`; `:ok | {:error, reason}`. Runs INSIDE the transaction."
  @type audit :: (String.t(), String.t(), %{optional(String.t()) => String.t()} -> :ok | {:error, term()})

  @doc """
  One step of the two-phase rotation (HY12). Option `:audit` (see `t:audit/0`) is REQUIRED: no caller can silently skip the audit row.

    * no `next` row: `{:ok, {:published, kid, activate_after}}` (`activate_after` is a `DateTime`), audit action
      `oauth_signing_key_published`; `{:error, :no_active_key}` when there is nothing to rotate yet;
    * a `next` row younger than 900 s: `{:error, {:too_early, seconds_left}}`, nothing changes;
    * a ripe `next` row that does not load: `{:error, :next_key_unavailable}`, nothing changes;
    * a ripe, loadable `next` row: the active key is retired (`not_after = now() + 900 s`) and `next` becomes
      active, ONE transaction: `{:ok, {:activated, new_kid, retired_kid}}` (action `oauth_signing_key_rotated`);
    * lost race: `{:error, :conflict}`. A caller that saw one state of the `next` row BEFORE it got the rotation lock
      and finds a different one AFTER it (another operator published, promoted or discarded the key meanwhile)
      answers `:conflict` and changes nothing: it never publishes a second `next` key on top of a rotation that
      just completed. A database error is `{:error, :storage}`; everything is rolled back.

  Never raises, never returns or logs key material.
  """
  @spec rotate(keyword()) :: {:ok, tuple()} | {:error, term()}
  def rotate(opts) when is_list(opts) do
    audit = Keyword.fetch!(opts, :audit)
    run_tx(fn repo -> do_rotate(repo, audit) end)
  end

  @doc """
  Emergency replacement of an active key that cannot be decrypted any more (HY13): in ONE transaction the
  active key and any `next` row are retired and a freshly generated `active` key is inserted (a `next` row is
  never promoted: it may be undecryptable under the same secret change). The old PUBLIC key stays in the JWKS
  until `not_after = now() + 900 s`. `{:ok, {:replaced, new_kid, old_kid}}` (audit action
  `oauth_signing_key_replaced`), `{:error, :no_active_key | :key_unavailable | :conflict | :storage}`.
  """
  @spec replace_emergency(keyword()) :: {:ok, tuple()} | {:error, term()}
  def replace_emergency(opts) when is_list(opts) do
    audit = Keyword.fetch!(opts, :audit)
    run_tx(fn repo -> do_replace(repo, audit) end)
  end

  defp run_tx(fun) do
    repo = repo()

    case repo.transaction(fn -> fun.(repo) end, timeout: 30_000) do
      {:ok, result} -> {:ok, result}
      {:error, reason} -> {:error, reason}
    end
  rescue
    e ->
      Logger.warning("OAuth signing key rotation failed: #{inspect(e.__struct__)}")
      {:error, :storage}
  catch
    :exit, _ ->
      Logger.warning("OAuth signing key rotation failed: exit")
      {:error, :storage}
  end

  # One advisory lock key for every rotation / replacement (transaction scoped: released at COMMIT / ROLLBACK).
  @sql_rotation_lock "SELECT pg_advisory_xact_lock(hashtext('nebu_oauth_signing_key_rotation'))"
  @sql_next_kid "SELECT kid FROM oauth_signing_keys WHERE status = 'next'"

  defp take_rotation_lock(repo) do
    case query(@sql_rotation_lock, []) do
      {:ok, _} -> :ok
      {:error, e} -> repo.rollback(db_reason(e))
    end
  end

  defp next_kid(repo) do
    case query(@sql_next_kid, []) do
      {:ok, %{rows: []}} -> nil
      {:ok, %{rows: [[kid]]}} -> kid
      {:ok, _} -> repo.rollback(:conflict)
      {:error, e} -> repo.rollback(db_reason(e))
    end
  end

  defp do_rotate(repo, audit) do
    # Snapshot of the `next` row BEFORE the lock, compare AFTER it: if another operator got through in between, the
    # state this call decided on is gone and it must not act on the new one (READ COMMITTED would otherwise let a
    # late caller see "no next key" and publish a second one right after the first caller's promotion).
    seen = next_kid(repo)
    :ok = take_rotation_lock(repo)
    if next_kid(repo) != seen, do: repo.rollback(:conflict)

    case query(@sql_next_for_update, []) do
      {:ok, %{rows: []}} -> publish_next(repo, audit)
      {:ok, %{rows: [[_kid, _pub, _enc, false, left]]}} -> repo.rollback({:too_early, left})
      {:ok, %{rows: [[kid, pub, enc, true, _left]]}} -> promote_next(repo, audit, kid, decode_json(pub), enc)
      {:ok, _} -> repo.rollback(:conflict)
      {:error, e} -> repo.rollback(db_reason(e))
    end
  end

  defp publish_next(repo, audit) do
    with {:ok, active_kid} <- active_kid(repo),
         {:ok, kid, public_json, enc} <- generate_key(repo) do
      case query(@sql_insert_next, [kid, public_json, enc]) do
        {:ok, %{rows: [[%DateTime{} = activate_after]]}} ->
          audit!(repo, audit, "oauth_signing_key_published", kid, %{"next_kid" => kid, "active_kid" => active_kid})
          Logger.info("OAuth signing key: published next ES256 key kid=#{kid}")
          {:published, kid, activate_after}

        {:ok, _} ->
          repo.rollback(:conflict)

        {:error, e} ->
          repo.rollback(db_reason(e))
      end
    else
      {:error, reason} -> repo.rollback(reason)
    end
  end

  defp promote_next(repo, audit, next_kid, public, enc) do
    case load_row(next_kid, public, enc) do
      {:ok, _key} -> :ok
      {:error, _} -> repo.rollback(:next_key_unavailable)
    end

    old_kid =
      case query(@sql_retire_active, []) do
        {:ok, %{rows: [[kid]]}} -> kid
        {:ok, %{rows: []}} -> nil
        {:ok, _} -> repo.rollback(:conflict)
        {:error, e} -> repo.rollback(db_reason(e))
      end

    case query(@sql_promote, [next_kid]) do
      {:ok, %{num_rows: 1}} -> :ok
      {:ok, _} -> repo.rollback(:no_next_key)
      {:error, e} -> repo.rollback(db_reason(e))
    end

    metadata = %{"new_kid" => next_kid} |> then(&if(old_kid, do: Map.put(&1, "retired_kid", old_kid), else: &1))
    audit!(repo, audit, "oauth_signing_key_rotated", next_kid, metadata)
    Logger.info("OAuth signing key: activated kid=#{next_kid}, retired kid=#{old_kid || "none"}")
    {:activated, next_kid, old_kid}
  end

  defp do_replace(repo, audit) do
    :ok = take_rotation_lock(repo)

    with {:ok, kid, public_json, enc} <- generate_key(repo) do
      case query(@sql_retire_next, []) do
        {:ok, _} -> :ok
        {:error, e} -> repo.rollback(db_reason(e))
      end

      old_kid =
        case query(@sql_retire_active, []) do
          {:ok, %{rows: [[old]]}} -> old
          {:ok, %{rows: []}} -> repo.rollback(:no_active_key)
          {:ok, _} -> repo.rollback(:conflict)
          {:error, e} -> repo.rollback(db_reason(e))
        end

      case query(@sql_insert_active_strict, [kid, public_json, enc]) do
        {:ok, %{num_rows: 1}} -> :ok
        {:ok, _} -> repo.rollback(:conflict)
        {:error, e} -> repo.rollback(db_reason(e))
      end

      audit!(repo, audit, "oauth_signing_key_replaced", kid, %{"new_kid" => kid, "retired_kid" => old_kid})
      Logger.info("OAuth signing key: emergency replacement kid=#{kid}, retired kid=#{old_kid}")
      {:replaced, kid, old_kid}
    else
      {:error, reason} -> repo.rollback(reason)
    end
  end

  defp active_kid(_repo) do
    case query(@sql_active_kid, []) do
      {:ok, %{rows: [[kid]]}} -> {:ok, kid}
      {:ok, %{rows: []}} -> {:error, :no_active_key}
      {:ok, _} -> {:error, :conflict}
      {:error, e} -> {:error, db_reason(e)}
    end
  end

  # `{:ok, kid, public_json, ciphertext}`; the private key never leaves this function except as ciphertext.
  defp generate_key(_repo) do
    jwk = JOSE.JWK.generate_key({:ec, "P-256"})
    kid = JOSE.JWK.thumbprint(jwk)
    {_, public_map} = JOSE.JWK.to_public_map(jwk)
    {_, private_map} = JOSE.JWK.to_map(jwk)
    {:ok, kid, Jason.encode!(public_map), Nebu.Web.SecretBox.encrypt(Jason.encode!(private_map))}
  rescue
    _ -> {:error, :key_unavailable}
  end

  defp audit!(repo, audit, action, kid, metadata) do
    result =
      try do
        audit.(action, kid, metadata)
      rescue
        e -> {:error, e.__struct__}
      end

    case result do
      :ok -> :ok
      {:error, reason} -> repo.rollback({:audit, reason})
      other -> repo.rollback({:audit, other})
    end
  end

  defp db_reason(%Postgrex.Error{postgres: %{code: code}}) when code in [:unique_violation, :check_violation, :serialization_failure, :deadlock_detected],
    do: :conflict

  defp db_reason(_other), do: :storage

  # ── internals ──────────────────────────────────────────────────────────────

  defp load_active do
    case query(@sql_active, []) do
      {:ok, %{rows: []}} -> {:ok, nil}
      {:ok, %{rows: [[kid, pub, enc]]}} -> load_row(kid, decode_json(pub), enc)
      {:ok, _} -> {:error, :key_inconsistent}
      {:error, _} -> {:error, :storage}
    end
  end

  defp generate_and_load do
    jwk = JOSE.JWK.generate_key({:ec, "P-256"})
    kid = JOSE.JWK.thumbprint(jwk)
    {_, public_map} = JOSE.JWK.to_public_map(jwk)
    {_, private_map} = JOSE.JWK.to_map(jwk)
    # Raises without an internal SecretBox secret: rescued by ensure_active_key/0 (type logged only).
    enc = Nebu.Web.SecretBox.encrypt(Jason.encode!(private_map))

    case query(@sql_insert, [kid, Jason.encode!(public_map), enc]) do
      {:ok, %{num_rows: 1}} -> Logger.info("OAuth signing key: generated a new ES256 key kid=#{kid}")
      {:ok, _} -> :ok
      {:error, _} -> :ok
    end

    case load_active() do
      {:ok, nil} -> {:error, :storage}
      other -> other
    end
  end

  defp load_row(kid, %{} = stored_public, enc) when is_binary(kid) and is_binary(enc) do
    case cache_get(kid, enc) do
      {:ok, jwk} ->
        {:ok, %{kid: kid, jwk: jwk}}

      :miss ->
        with {:ok, plain} <- decrypt(enc),
             {:ok, %{} = private_map} <- Jason.decode(plain),
             %JOSE.JWK{} = jwk <- from_map(private_map),
             true <- JOSE.JWK.thumbprint(jwk) == kid,
             {_, public_map} = JOSE.JWK.to_public_map(jwk),
             true <- same_public?(public_map, stored_public) do
          cache_put(kid, enc, jwk)
          {:ok, %{kid: kid, jwk: jwk}}
        else
          :decrypt_failed -> {:error, :key_unavailable}
          _ -> {:error, :key_inconsistent}
        end
    end
  end

  defp load_row(_kid, _pub, _enc), do: {:error, :key_inconsistent}

  defp decrypt(enc) do
    case Nebu.Web.SecretBox.decrypt(enc) do
      {:ok, plain} when is_binary(plain) -> {:ok, plain}
      _ -> :decrypt_failed
    end
  rescue
    _ -> :decrypt_failed
  end

  defp from_map(map) do
    JOSE.JWK.from_map(map)
  rescue
    _ -> :invalid
  end

  defp same_public?(a, b) do
    keys = ~w(kty crv x y)
    Map.take(a, keys) == Map.take(b, keys) and Map.get(a, "kty") == "EC" and Map.get(a, "crv") == "P-256"
  end

  defp public_member_map(pub, kid) do
    pub
    |> Map.take(~w(kty crv x y))
    |> Map.merge(%{"kid" => kid, "use" => "sig", "alg" => @alg})
  end

  defp decode_json(%{} = map), do: map

  defp decode_json(text) when is_binary(text) do
    case Jason.decode(text) do
      {:ok, %{} = map} -> map
      _ -> %{}
    end
  end

  defp decode_json(_), do: %{}

  # ── per-node cache of DECODED key material (immutable rows; keyed by kid + ciphertext) ──
  # Table owned by Nebu.OAuth.CacheOwner (HY4); an absent table is a miss / a skipped write, never created here.

  defp cache_get(kid, enc) do
    case :ets.lookup(@cache_table, kid) do
      [{^kid, ^enc, jwk}] -> {:ok, jwk}
      _ -> :miss
    end
  rescue
    ArgumentError -> :miss
  end

  defp cache_put(kid, enc, jwk) do
    :ets.insert(@cache_table, {kid, enc, jwk})
    :ok
  rescue
    ArgumentError -> :ok
  end

  defp repo, do: Application.get_env(:nebu_http, :oauth_repo, Nebu.Repo)

  # Never `inspect` an exception carrying parameters (the ciphertext is a parameter).
  defp query(sql, params) do
    Ecto.Adapters.SQL.query(repo(), sql, params)
  rescue
    e in [RuntimeError, ArgumentError, UndefinedFunctionError, DBConnection.ConnectionError, DBConnection.EncodeError] ->
      {:error, e}
  catch
    :exit, reason -> {:error, {:exit, reason}}
  end
end
