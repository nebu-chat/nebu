defmodule Nebu.Matrix.SsoStore do
  @moduledoc """
  Cluster-aware, single-use, TTL-bounded state store for the Matrix client SSO
  flow (`bugfix-fix-matrix-sso-redirect-missing`, Go parity with the removed
  `gateway/internal/matrix/sso.go` `ssoStateStore` + `loginTokenStore`).

  Three short-lived stores live here:

    * **SSO state** (keyed by the opaque CSRF `state`): `{verifier, nonce,
      redirect_url, exp}`. Generated by `GET .../sso/redirect`, consumed
      (single-use `pop`) by the callback. TTL 10 minutes (the user-typing-at-IdP
      window).
    * **Login token** (keyed by an opaque 256-bit token): the verified OIDC
      `id_token` string. Minted by the callback, consumed (single-use `pop`) by
      `POST /login`. TTL 30 seconds — the token traverses browser history /
      Referer / proxy logs, so the replay window is kept tiny.
    * **Pending confirmation** (story `legacy-sso-redirect-confirmation`, G3-3, tag `:confirm`): keyed by the RAW
      SHA-256 digest of the browser-binding cookie, holding the verified `id_token`, the IdP refresh token, the
      redirect URL and the display fields of an UNLISTED https target, BEFORE any loginToken exists. Written by the
      callback, read (`peek_confirm/1`, directly from the ETS table, no process call) by the confirmation page and consumed (`pop_confirm/1`, single use) by its
      POST. TTL 300 s, own cap of 10 000 entries per node. Same cluster properties as the loginToken store
      (`pg` replication, single use atomic per node, best effort across nodes, volatile).

  ## Why a supervised GenServer + `pg` (ADR-020 cluster-readiness)

  A Matrix client makes the initial `/sso/redirect` request itself and then opens
  the `Location` URL in a browser; the callback and the `POST /login` can each land
  on a *different* cluster node behind the load balancer. A node-local
  `Map`/ETS would make the flow fail whenever those hops hit different nodes.

  This store therefore behaves identically on one node and in a cluster:

    * Each node runs one `SsoStore` GenServer that owns a named, `:protected`, `read_concurrency` ETS table (`peek_confirm/1` reads it directly, every write and `pop_*` goes through the process) and
      joins the `nebu_matrix_sso_store` process group (`pg`, the project's built-in
      pub/sub — ADR-002/020).
    * Every `put_*` / `pop_*` is **broadcast** to all group members, so each node
      keeps a replica. A `pop` is a single-use delete broadcast as a tombstone.
      Within a single node a `pop` is atomic (serialized in the one GenServer), so a
      token can be redeemed exactly once. **Across nodes** replication is async
      (`pg` broadcast via `send/2`, eventually consistent), so two simultaneous
      redemptions of the same token landing on different nodes within the
      sub-millisecond propagation window could both succeed — i.e. cross-node
      single-use is best-effort, not consensus-backed (mirrors the removed Go
      `sso.go` store). The exposure is bounded by the 30-second loginToken TTL,
      single-use-per-node, and the fact that the token is the legitimate user's own.
      True cross-node atomicity (owner-routing via Horde, or a DB
      `DELETE … RETURNING`) is tracked as deferred follow-up work; single-node
      deployments are unaffected.
    * Entries carry an absolute `exp` (monotonic-free unix seconds); a lookup
      treats an expired entry as absent and lazily deletes it, and a periodic
      sweep evicts stale rows so the tables never grow without bound.

  Volatile by design (like `Nebu.Web.TokenDenylist`): on a full-cluster restart a
  pending SSO flow is lost and the user simply re-initiates — acceptable for a
  10-minute / 30-second window.
  """
  use GenServer

  require Logger

  @table __MODULE__.Table
  @pg_group "nebu_matrix_sso_store"

  # Periodic eviction of expired rows (defence against unbounded growth from
  # unauthenticated /sso/redirect spray — Go ssoStateStoreMaxEntries analogue).
  @sweep_interval_ms 60_000

  # Hard cap on pending SSO states to bound memory under an unauthenticated flood
  # (Go: ssoStateStoreMaxEntries = 10_000).
  @max_state_entries 10_000
  @max_token_entries 10_000
  @max_confirm_entries 10_000

  # The fields of a pending confirmation entry (D7); nothing else is ever stored.
  @confirm_fields ~w(id_token oidc_refresh_token redirect_url origin host port path user_id)a

  # ── Public API ──────────────────────────────────────────────────────────────

  def start_link(_opts \\ []), do: GenServer.start_link(__MODULE__, :ok, name: __MODULE__)

  @doc """
  Persist a pending SSO `state` entry for `ttl_seconds`. `entry` is a map with
  `:verifier`, `:nonce`, `:redirect_url`. Returns `:ok`, or `{:error, :store_full}`
  when the per-node state cap is exceeded (the caller answers 429/limit).
  """
  @spec put_state(String.t(), map(), non_neg_integer()) :: :ok | {:error, :store_full | :unavailable}
  def put_state(state, entry, ttl_seconds)
      when is_binary(state) and is_map(entry) and is_integer(ttl_seconds) do
    call({:put_state, state, normalize_state(entry), exp_at(ttl_seconds)}, {:error, :unavailable})
  end

  @doc "Single-use read of a pending SSO state. `{:ok, %{verifier, nonce, redirect_url}}` or `:error`."
  @spec pop_state(String.t()) :: {:ok, map()} | :error
  def pop_state(state) when is_binary(state) do
    call({:pop_state, state}, :error)
  end

  @doc "Non-destructive read of a pending SSO state (used by tests / diagnostics)."
  @spec peek_state(String.t()) :: {:ok, map()} | :error
  def peek_state(state) when is_binary(state) do
    call({:peek_state, state}, :error)
  end

  @doc """
  Mint an opaque login token mapped to the verified `id_token` for `ttl_seconds`.

  `opts` may carry `:oidc_refresh_token` — the OIDC refresh token captured during
  the SSO code exchange (oidc-session-refresh). It is stored ALONGSIDE the
  `id_token` so `POST /login` can mint a long-lived opaque Nebu session
  (`refresh_token: true`). The stored value is encrypted by the caller before it
  reaches here when it must be persisted; in the login-token store it lives only
  for the (default 30s) single-use TTL window in memory. `nil` (the default) keeps
  the legacy behaviour — no OIDC RT available, JWT fallback (AC7).
  """
  @spec put_login_token(String.t(), String.t(), integer(), keyword()) :: :ok | {:error, :store_full | :unavailable}
  def put_login_token(token, id_token, ttl_seconds, opts \\ [])
      when is_binary(token) and is_binary(id_token) and is_integer(ttl_seconds) and is_list(opts) do
    oidc_rt = Keyword.get(opts, :oidc_refresh_token)
    payload = %{id_token: id_token, oidc_refresh_token: oidc_rt}
    call({:put_token, token, payload, exp_at(ttl_seconds)}, {:error, :unavailable})
  end

  @doc """
  Single-use redemption of a login token. Returns
  `{:ok, id_token, oidc_refresh_token}` (the OIDC RT is `nil` when none was
  captured) or `:error`. The 3-tuple feeds the opaque-session login path; callers
  that only need the id_token ignore the third element.
  """
  @spec pop_login_token(String.t()) :: {:ok, String.t(), String.t() | nil} | :error
  def pop_login_token(token) when is_binary(token) do
    case call({:pop_token, token}, :error) do
      {:ok, %{id_token: id_token, oidc_refresh_token: oidc_rt}} -> {:ok, id_token, oidc_rt}
      # Backward-compat: a token minted before this change stored a bare id_token.
      {:ok, id_token} when is_binary(id_token) -> {:ok, id_token, nil}
      :error -> :error
    end
  end

  @doc """
  Persist a pending confirmation `entry` (`%{id_token, oidc_refresh_token, redirect_url, origin, host, port, path,
  user_id}`) under `key` (the RAW SHA-256 digest of the browser-binding cookie, never the cookie itself) for
  `ttl_seconds`. A second put under the same key replaces the entry. `{:error, :store_full}` when the per-node cap
  of #{@max_confirm_entries} live `:confirm` entries is reached (expired entries are evicted first).
  """
  @spec put_confirm(binary(), map(), integer()) :: :ok | {:error, :store_full | :unavailable}
  def put_confirm(key, entry, ttl_seconds) when is_binary(key) and is_map(entry) and is_integer(ttl_seconds) do
    call({:put_confirm, key, Map.take(entry, @confirm_fields), exp_at(ttl_seconds)}, {:error, :unavailable})
  end

  @doc """
  Non-destructive read of a pending confirmation (the page render; a reload is safe). `{:ok, entry}` or `:error`.

  Story admin-config-audit-atomic D6 (follow-up `di`, SEC delta gate X2-5): read DIRECTLY from the named, `:protected`, `read_concurrency` ETS table
  of this node, no call to the store process. The page lookup of every request (also a flood of well-formed random cookies) is therefore not queued
  behind `put_state`, the loginToken mint and the `/login` redemption of every legacy SSO user. An expired entry is `:error` (the sweep and `pop_confirm/1`
  delete it, a reader cannot); a missing table (the store is not started) is `:error` too.
  """
  @spec peek_confirm(binary()) :: {:ok, map()} | :error
  def peek_confirm(key) when is_binary(key) do
    case :ets.lookup(@table, {:confirm, key}) do
      [{_key, {payload, exp}}] -> if now() < exp, do: {:ok, payload}, else: :error
      _ -> :error
    end
  rescue
    ArgumentError ->
      warn_unavailable(:noproc)
      :error
  end

  @doc "Single-use read of a pending confirmation (the POST): deletes it and broadcasts the tombstone. `{:ok, entry}` or `:error`."
  @spec pop_confirm(binary()) :: {:ok, map()} | :error
  def pop_confirm(key) when is_binary(key), do: call({:pop_confirm, key}, :error)

  # Security review SEC #2 (Logging Law): a `GenServer.call` timeout / `noproc` of this node-local process makes the
  # CALLER exit with the whole call message (id_token, IdP refresh token, redirect URL, loginToken) in its crash
  # report, and `format_status/1` only redacts the store's OWN report. Every call therefore catches the exit and
  # answers `unavailable_value` (`{:error, :unavailable}` for a `put_*`, `:error` for a `pop_*` / `peek_*`), which
  # the HTTP surface maps to a 503 / 400 answer. The timeout is 5000 ms; the seam
  # `:nebu_http, :sso_store_call_timeout_ms` (compile-guarded, test builds only) shortens it for the tests.
  defp call(message, unavailable_value) do
    GenServer.call(__MODULE__, message, call_timeout_ms())
  catch
    :exit, reason ->
      warn_unavailable(reason)
      unavailable_value
  end

  # ONE WARNING per minute per node, naming only the exit TAG (`timeout`, `noproc`, ...): never the reason (it
  # carries the call message) and never a value. Log-volume control only (node-local bucket), never correctness.
  defp warn_unavailable(reason) do
    tag =
      case reason do
        {tag, _detail} when is_atom(tag) -> tag
        tag when is_atom(tag) -> tag
        _ -> :unknown
      end

    if Nebu.Web.Plugs.RateLimit.take({"sso_store_unavailable_warning", :node}, 1, 1) == :ok do
      Logger.warning("matrix SSO: the SSO store did not answer reason=#{tag}")
    end
  rescue
    _ -> :ok
  end

  if Mix.env() == :test do
    defp call_timeout_ms, do: Application.get_env(:nebu_http, :sso_store_call_timeout_ms, 5_000)
  else
    defp call_timeout_ms, do: 5_000
  end

  # ── GenServer ────────────────────────────────────────────────────────────────

  @impl true
  def init(:ok) do
    table = :ets.new(@table, [:named_table, :set, :protected, read_concurrency: true])
    ensure_pg()
    :pg.join(@pg_group, self())
    schedule_sweep()
    {:ok, %{table: table}}
  end

  @impl true
  def handle_call({:put_state, state, entry, exp}, _from, %{table: table} = s) do
    if state_count(table) >= @max_state_entries do
      evict_expired(table)

      if state_count(table) >= @max_state_entries do
        {:reply, {:error, :store_full}, s}
      else
        do_put(table, {:state, state}, {entry, exp})
        {:reply, :ok, s}
      end
    else
      do_put(table, {:state, state}, {entry, exp})
      {:reply, :ok, s}
    end
  end

  def handle_call({:put_token, token, id_token, exp}, _from, %{table: table} = s) do
    # F-1 (Kassandra MEDIUM): cap the login-token map symmetrically with the state
    # map so a flood of completed-but-unredeemed flows cannot grow the table without
    # bound (defence-in-depth on top of the IdP-rate-limited, state-capped mint path).
    if token_count(table) >= @max_token_entries do
      evict_expired(table)

      if token_count(table) >= @max_token_entries do
        {:reply, {:error, :store_full}, s}
      else
        do_put(table, {:token, token}, {id_token, exp})
        {:reply, :ok, s}
      end
    else
      do_put(table, {:token, token}, {id_token, exp})
      {:reply, :ok, s}
    end
  end

  def handle_call({:put_confirm, key, entry, exp}, _from, %{table: table} = s) do
    if confirm_count(table) >= @max_confirm_entries do
      evict_expired(table)

      if confirm_count(table) >= @max_confirm_entries do
        {:reply, {:error, :store_full}, s}
      else
        do_put(table, {:confirm, key}, {entry, exp})
        {:reply, :ok, s}
      end
    else
      do_put(table, {:confirm, key}, {entry, exp})
      {:reply, :ok, s}
    end
  end

  def handle_call({:pop_confirm, key}, _from, %{table: table} = s) do
    {:reply, do_pop(table, {:confirm, key}), s}
  end

  def handle_call({:pop_state, state}, _from, %{table: table} = s) do
    {:reply, do_pop(table, {:state, state}), s}
  end

  def handle_call({:pop_token, token}, _from, %{table: table} = s) do
    {:reply, do_pop(table, {:token, token}), s}
  end

  def handle_call({:peek_state, state}, _from, %{table: table} = s) do
    {:reply, lookup_live(table, {:state, state}), s}
  end

  # ── Cluster replication (pg broadcast) ──────────────────────────────────────
  # A peer node forwarded a write/delete; apply it to the local replica. These are
  # casts (no reply) so a peer is never blocked on us.

  @impl true
  def handle_info({:replicate_put, key, value}, %{table: table} = s) do
    :ets.insert(table, {key, value})
    {:noreply, s}
  end

  def handle_info({:replicate_delete, key}, %{table: table} = s) do
    :ets.delete(table, key)
    {:noreply, s}
  end

  def handle_info(:sweep, %{table: table} = s) do
    evict_expired(table)
    schedule_sweep()
    {:noreply, s}
  end

  def handle_info(_other, s), do: {:noreply, s}

  # ── Crash-report hardening (story legacy-sso-redirect-confirmation, D7) ─────
  # A crash report or `:sys.get_status/1` of this process must never print a loginToken, an id_token, an IdP
  # refresh token, a redirect URL or a binding-cookie hash: every message payload (`:put_token`, `:put_confirm`,
  # `:replicate_put`, ...) and the table are replaced by a tag. There is deliberately NO `handle_cast/2`.
  @impl true
  def format_status(status) when is_map(status) do
    Map.new(status, fn
      {:state, _state} -> {:state, %{table: :redacted}}
      {:message, message} -> {:message, redact_message(message)}
      {:log, log} when is_list(log) -> {:log, Enum.map(log, &redact_log_event/1)}
      {:reason, {:bad_cast, _message}} -> {:reason, {:bad_cast, :redacted}}
      other -> other
    end)
  end

  defp redact_message({:"$gen_call", from, request}), do: {:"$gen_call", from, redact_message(request)}
  defp redact_message({:"$gen_cast", request}), do: {:"$gen_cast", redact_message(request)}
  defp redact_message(message) when is_tuple(message) and tuple_size(message) > 0 and is_atom(elem(message, 0)), do: {elem(message, 0), :redacted}
  defp redact_message(message) when is_atom(message), do: message
  defp redact_message(_message), do: :redacted

  defp redact_log_event({:in, message}), do: {:in, redact_message(message)}
  defp redact_log_event({:in, message, from}), do: {:in, redact_message(message), from}
  defp redact_log_event({:out, _message, to, _state}), do: {:out, :redacted, to, :redacted}
  defp redact_log_event(_other), do: :redacted

  # ── Internals ────────────────────────────────────────────────────────────────

  # Write locally, then broadcast to every OTHER node's replica.
  defp do_put(table, key, value) do
    :ets.insert(table, {key, value})
    broadcast({:replicate_put, key, value})
    :ok
  end

  # Single-use read: look up a live (non-expired) entry, delete it locally, and
  # broadcast the tombstone so no other node can redeem it again.
  defp do_pop(table, key) do
    case lookup_live(table, key) do
      {:ok, _value} = ok ->
        :ets.delete(table, key)
        broadcast({:replicate_delete, key})
        ok

      :error ->
        # Expired/unknown: still broadcast a delete so a stale replica is cleaned.
        :ets.delete(table, key)
        broadcast({:replicate_delete, key})
        :error
    end
  end

  # Returns {:ok, payload} for a non-expired entry, else :error (and lazily deletes
  # an expired one locally). `payload` is the stored value WITHOUT the exp.
  defp lookup_live(table, key) do
    case :ets.lookup(table, key) do
      [{^key, {payload, exp}}] ->
        if now() < exp do
          {:ok, payload}
        else
          :ets.delete(table, key)
          :error
        end

      _ ->
        :error
    end
  end

  defp evict_expired(table) do
    now = now()

    :ets.foldl(
      fn {key, {_payload, exp}}, acc ->
        if now >= exp, do: [key | acc], else: acc
      end,
      [],
      table
    )
    |> Enum.each(&:ets.delete(table, &1))
  end

  defp state_count(table), do: count_by_tag(table, :state)
  defp token_count(table), do: count_by_tag(table, :token)
  defp confirm_count(table), do: count_by_tag(table, :confirm)

  defp count_by_tag(table, tag) do
    :ets.foldl(fn {{t, _}, _}, acc when t == tag -> acc + 1; _, acc -> acc end, 0, table)
  end

  # Normalise a caller map to a stable string-keyed-free struct-shape map.
  defp normalize_state(entry) do
    %{
      verifier: entry[:verifier] || entry["verifier"],
      nonce: entry[:nonce] || entry["nonce"],
      redirect_url: entry[:redirect_url] || entry["redirect_url"],
      # S3: a UIA auth-fallback flow tags the state with the UIA session id so the
      # shared OIDC callback can complete THAT UIA session instead of minting a
      # normal loginToken. nil for an ordinary login redirect.
      uia_session: entry[:uia_session] || entry["uia_session"]
    }
  end

  defp broadcast(msg) do
    self_pid = self()

    for pid <- :pg.get_members(@pg_group), pid != self_pid do
      send(pid, msg)
    end

    :ok
  end

  defp ensure_pg do
    case :pg.start_link() do
      {:ok, _} -> :ok
      {:error, {:already_started, _}} -> :ok
      _ -> :ok
    end
  end

  defp schedule_sweep, do: Process.send_after(self(), :sweep, @sweep_interval_ms)

  defp exp_at(ttl_seconds), do: now() + ttl_seconds
  defp now, do: System.system_time(:second)
end
